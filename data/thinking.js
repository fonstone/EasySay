const TYPE_MAP = {}
TYPES.forEach(t => { TYPE_MAP[t.id] = t })
QUESTIONS.forEach(q => {
  const t = TYPE_MAP[q.type] || {}
  q.typeName = t.name || ''
  q.typeShort = t.short || ''
  q.typeGlyph = t.glyph || ''
  q.typeColor = t.color || '#1B5A47'
  q.typeSoft = t.soft || '#E4F0EA'
})

function getQuestion(id) {
  return QUESTIONS.find(q => q.id === id) || null
}

function getQuestions(typeId) {
  return typeId ? QUESTIONS.filter(q => q.type === typeId) : QUESTIONS
}

function getType(id) {
  return TYPE_MAP[id] || null
}

module.exports = {
  TYPES,
  QUESTIONS,
  getQuestion,
  getQuestions,
  getType
}
